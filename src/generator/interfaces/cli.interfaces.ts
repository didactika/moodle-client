import type * as readline from "node:readline/promises";

/**
 * Values of the schema entry flags (`--namespace`, `--source.*`, `--webservices`, `--outDir`),
 * exactly as typed on the command line. Each one mirrors a key of a
 * "moodle-client" entry in package.json.
 */
export interface SchemaEntryFlags {
    namespace?: string;
    sourceType?: string;
    sourceVersion?: string;
    sourceUrl?: string;
    sourceBranch?: string;
    sourcePath?: string;
    webservices?: string;
    outDir?: string;
}

/**
 * Options accepted by the main schema generator CLI (`moodle-generate-schemas`).
 */
export interface CliOptions {
    configPath?: string;
    force?: boolean;
    /** Namespaces given with --namespace: only these are regenerated from scratch */
    namespaces?: string[];
    help?: boolean;
}

/**
 * Options accepted by the schema creation CLI (`moodle-create-schemas`).
 * When `entry` is set the CLI runs without prompts.
 */
export interface CreateCliOptions {
    configPath?: string;
    entry?: SchemaEntryFlags;
    help?: boolean;
}

/**
 * Options accepted by the schema update CLI (`moodle-update-schemas`).
 * When `entry` is set the CLI runs without prompts.
 */
export interface UpdateCliOptions {
    configPath?: string;
    entry?: SchemaEntryFlags;
    /** Regenerate the namespace after saving (`--sync`) */
    sync?: boolean;
    help?: boolean;
}

/**
 * Options accepted by the schema deletion CLI (`moodle-delete-schemas`).
 * When `namespace` is set the CLI runs without prompts.
 */
export interface DeleteCliOptions {
    configPath?: string;
    namespace?: string;
    /** Also delete files in the namespace directory that were not generated by moodle-client */
    purge?: boolean;
    help?: boolean;
}

/**
 * Execution context for interactive readline prompts, supporting dependency injection for testing.
 */
export interface PromptContext {
    rl?: readline.Interface;
    mockAnswers?: string[];
    input?: NodeJS.ReadableStream;
    output?: NodeJS.WritableStream;
}
